void Map::LoadGraphics() {
    // グラフィックの読み込み
    imgPlayer = LoadGraph("../assets/robo_x11.png");
    imgFloor = LoadGraph("../assets/tfloor.png"); 
    imgWall = LoadGraph("../assets/twall.png");
}

void Map::DeleteGraphics() {
    // グラフィックの解放
    DeleteGraph(imgFloor);
    DeleteGraph(imgWall);
    DeleteGraph(imgPlayer);
}

void Map::DrawMap() const {
    for (int j = 0; j < mapHeight; ++j) {
        for (int i = 0; i < mapWidth; ++i) {
            // 描画する座標を計算する
            int x = i * MapChipsize;
            int y = j * MapChipsize;

            // mapDataを参照して背景かブロックかを描き分ける
            if (mapData[j][i] == 0) {
                // 床
                DrawGraph(x, y, imgFloor, FALSE);
            }
            else if (mapData[j][i] == 1 || mapData[j][i] == 2 || mapData[j][i] == 3) {
                // 壁やドア
                DrawGraph(x, y, imgWall, TRUE);
            }
        }
    }
}